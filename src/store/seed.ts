const now = Date.now()

export function createSeedTree(): DocNode[] {
  const file = (id: string, name: string, content: string): DocNode => ({
    id,
    name,
    kind: 'file',
    content,
    createdAt: now,
    updatedAt: now,
    source: 'library',
  })

  return [
    file('welcome', '欢迎.md', welcome),
    {
      id: 'guides',
      name: '指南',
      kind: 'folder',
      createdAt: now,
      updatedAt: now,
      children: [
        file('syntax', 'Markdown 基础.md', syntax),
        file('math', '数学、代码与图表.md', math),
        file('shortcuts', '键盘快捷键.md', shortcuts),
      ],
    },
  ]
}
